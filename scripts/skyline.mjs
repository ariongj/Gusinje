// The ring of peaks around Vusanje, drawn from elevation data for the home
// page: node scripts/skyline.mjs → src/content/skyline.ts
//
// For each compass direction from Vusanje the script finds the highest ground
// within each distance band — the crest of the massifs (far band, behind) and
// the nearer ridges (in front). Heights are metres above sea level, so the
// drawing is a profile, not a photograph-like view from one spot; the summits
// sit on the line by construction.
//
// Elevation: Mapzen terrain tiles (terrarium encoding, SRTM and others) on AWS
// Open Data — the same data as the 3D map. Tiles are cached in DEM_CACHE.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const CACHE = process.env.DEM_CACHE || join(process.cwd(), ".dem-cache");
const Z = 12;
const CENTRE = { slug: "vusanje", lat: 42.52944, lng: 19.84028 }; // places.ts
const AZ = [100, 260]; // compass degrees, left to right: east, round by the south, to west
const STEP = 0.5; // degrees per sample
const NEAR = 1500; // metres: the valley floor and its first slopes are left out
const BANDS = [9000, 5500, 3200]; // metres: crest behind, nearer ridges in front
const PEAKS = [
  // Only places with sourced coordinates (places.ts).
  { slug: "karanfili", lat: 42.49639, lng: 19.78694 },
  { slug: "zla-kolata", lat: 42.485, lng: 19.89722 },
];
const R = 6371000;

mkdirSync(CACHE, { recursive: true });
const tiles = new Map();
const tileXY = (lat, lng) => {
  const n = 2 ** Z;
  const r = (lat * Math.PI) / 180;
  return [((lng + 180) / 360) * n, ((1 - Math.log(Math.tan(r) + 1 / Math.cos(r)) / Math.PI) / 2) * n];
};

async function tile(tx, ty) {
  const key = `${tx}/${ty}`;
  if (tiles.has(key)) return tiles.get(key);
  const file = join(CACHE, `${Z}-${tx}-${ty}.png`);
  if (!existsSync(file)) {
    execFileSync("curl", ["-sSf", "-m", "30", "-o", file, `https://elevation-tiles-prod.s3.amazonaws.com/terrarium/${Z}/${tx}/${ty}.png`]);
  }
  const { data, info } = await sharp(file).removeAlpha().raw().toBuffer({ resolveWithObject: true });
  const t = { data, size: info.width };
  tiles.set(key, t);
  return t;
}

async function elevation(lat, lng) {
  const [x, y] = tileXY(lat, lng);
  const tx = Math.floor(x);
  const ty = Math.floor(y);
  const t = await tile(tx, ty);
  const px = Math.min(t.size - 1.001, (x - tx) * t.size);
  const py = Math.min(t.size - 1.001, (y - ty) * t.size);
  const x0 = Math.floor(px);
  const y0 = Math.floor(py);
  const at = (ix, iy) => {
    const i = (iy * t.size + ix) * 3;
    return t.data[i] * 256 + t.data[i + 1] + t.data[i + 2] / 256 - 32768;
  };
  const fx = px - x0;
  const fy = py - y0;
  return at(x0, y0) * (1 - fx) * (1 - fy) + at(x0 + 1, y0) * fx * (1 - fy) + at(x0, y0 + 1) * (1 - fx) * fy + at(x0 + 1, y0 + 1) * fx * fy;
}

const toRad = (d) => (d * Math.PI) / 180;
const toDeg = (r) => (r * 180) / Math.PI;
function destination(lat, lng, azimuth, distance) {
  const d = distance / R;
  const a = toRad(azimuth);
  const p1 = toRad(lat);
  const l1 = toRad(lng);
  const p2 = Math.asin(Math.sin(p1) * Math.cos(d) + Math.cos(p1) * Math.sin(d) * Math.cos(a));
  const l2 = l1 + Math.atan2(Math.sin(a) * Math.sin(d) * Math.cos(p1), Math.cos(d) - Math.sin(p1) * Math.sin(p2));
  return [toDeg(p2), toDeg(l2)];
}
function bearing(lat1, lng1, lat2, lng2) {
  const p1 = toRad(lat1);
  const p2 = toRad(lat2);
  const dl = toRad(lng2 - lng1);
  return (toDeg(Math.atan2(Math.sin(dl) * Math.cos(p2), Math.cos(p1) * Math.sin(p2) - Math.sin(p1) * Math.cos(p2) * Math.cos(dl))) + 360) % 360;
}

const floor = await elevation(CENTRE.lat, CENTRE.lng);
const layers = BANDS.map(() => []);
for (let az = AZ[0]; az <= AZ[1] + 1e-9; az += STEP) {
  const best = BANDS.map(() => -Infinity);
  for (let d = NEAR; d <= BANDS[0]; d += 30) {
    const [lat, lng] = destination(CENTRE.lat, CENTRE.lng, az, d);
    const h = await elevation(lat, lng);
    BANDS.forEach((limit, i) => {
      if (d <= limit && h > best[i]) best[i] = h;
    });
  }
  best.forEach((h, i) => layers[i].push(Math.round(h)));
}

const peaks = PEAKS.map((p) => ({ slug: p.slug, azimuth: +bearing(CENTRE.lat, CENTRE.lng, p.lat, p.lng).toFixed(1) }));
const top = Math.max(...layers[0]);
const out = `// Generated by scripts/skyline.mjs from elevation data (Mapzen terrain tiles,
// SRTM and others, AWS Open Data). Do not edit by hand.

/**
 * The ring of peaks around ${CENTRE.slug}: for each compass direction, the highest
 * ground between ${NEAR / 1000} and ${BANDS[0] / 1000} km away (crest behind, nearer ridges in front).
 * Heights in metres above sea level; a profile, not a view from one spot.
 */
export const skyline = {
  centre: "${CENTRE.slug}",
  /** Compass directions at the left and right edges, in degrees. */
  azimuth: [${AZ[0]}, ${AZ[1]}] as const,
  /** Heights at the bottom and top of the drawing, in metres. */
  height: [${Math.round(floor / 50) * 50}, ${Math.ceil(top / 50) * 50}] as const,
  /** Distance limits of each layer in metres, far to near. */
  bands: [${BANDS.join(", ")}] as const,
  /** One height per ${STEP}° of compass direction, per layer (far to near). */
  layers: [
${layers.map((l) => `    [${l.join(",")}],`).join("\n")}
  ],
  /** Places with sourced coordinates, by compass direction. */
  peaks: ${JSON.stringify(peaks)},
} as const;
`;
writeFileSync(join(process.cwd(), "src/content/skyline.ts"), out);
console.log("floor", floor.toFixed(0), "m; top", top, "m; peaks", JSON.stringify(peaks), "; tiles", tiles.size);
